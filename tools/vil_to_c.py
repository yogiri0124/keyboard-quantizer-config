#!/usr/bin/env python3
"""Turn a Vial layout file (.vil) into the firmware's default configuration.

    vil_to_c.py default.vil quantum/vial_ensure_keycode.h > default_config.h

The header holds two parts: with KQ_DEFAULT_KEYMAP defined, the default
keymap (QMK's keymaps[], which QMK wants in keymap.c); with KQ_DEFAULT_DATA,
the tap dances, combos, key overrides, macros and QMK Settings that
default_config.c writes when the saved configuration is reset. Keycode names are resolved to numbers
here, from the names Vial itself uses (the _Static_assert table in the QMK
tree's quantum/vial_ensure_keycode.h), so the .vil works as saved by Vial.
"""

import json
import re
import sys

# Vial macro bytes (quantum/send_string/send_string_keycodes.h, quantum/vial.h).
SS_QMK_PREFIX = 1
SS_TAP, SS_DOWN, SS_UP, SS_DELAY = 1, 2, 3, 4
EXT_TAP, EXT_DOWN, EXT_UP = 5, 6, 7


def load_names(path):
    """NAME -> value and WRAPPER -> base, from _Static_assert lines."""
    names, wrappers = {}, {}
    pat = re.compile(r'_Static_assert\(\s*([A-Za-z_][A-Za-z0-9_]*)(\(kc\))?\s*==\s*(0x[0-9A-Fa-f]+|\d+)\s*,')
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = pat.search(line)
            if m:
                (wrappers if m.group(2) else names)[m.group(1)] = int(m.group(3), 0)
    return names, wrappers


class Resolver:
    def __init__(self, names, wrappers):
        self.names = names
        self.wrappers = wrappers

    def base(self, name):
        if name not in self.names:
            raise ValueError('unknown base ' + name)
        return self.names[name]

    def __call__(self, kc):
        if isinstance(kc, int):
            return 0 if kc < 0 else kc
        kc = kc.strip()
        if re.fullmatch(r'0x[0-9A-Fa-f]+|\d+', kc):
            return int(kc, 0)
        if kc in self.names:
            return self.names[kc]
        m = re.fullmatch(r'USER(\d+)', kc)
        if m:
            return self.base('QK_KB') + int(m.group(1))
        m = re.fullmatch(r'M(\d+)', kc)
        if m:
            return self.base('QK_MACRO') + int(m.group(1))
        m = re.fullmatch(r'(MO|TO|TG|DF|OSL|TT|TD)\((\d+)\)', kc)
        if m:
            bases = {'MO': 'QK_MOMENTARY', 'TO': 'QK_TO', 'TG': 'QK_TOGGLE_LAYER', 'DF': 'QK_DEF_LAYER',
                     'OSL': 'QK_ONE_SHOT_LAYER', 'TT': 'QK_LAYER_TAP_TOGGLE', 'TD': 'QK_TAP_DANCE'}
            return self.base(bases[m.group(1)]) | int(m.group(2))
        m = re.fullmatch(r'LT(\d+)\((.+)\)', kc)
        if m:
            return self.base('QK_LAYER_TAP') | (int(m.group(1)) << 8) | self(m.group(2))
        m = re.fullmatch(r'OSM\((.+)\)', kc)
        if m:
            return self.base('QK_ONE_SHOT_MOD') | self.mods(m.group(1))
        m = re.fullmatch(r'LM(\d+)\((.+)\)', kc)
        if m:
            return self.base('QK_LAYER_MOD') | (int(m.group(1)) << 5) | self.mods(m.group(2))
        m = re.fullmatch(r'([A-Z_]+)\((.+)\)', kc)
        if m and m.group(1) in self.wrappers:
            return self.wrappers[m.group(1)] | self(m.group(2))
        raise ValueError('unknown keycode ' + kc)

    def mods(self, expr):
        value = 0
        for part in expr.split('|'):
            value |= self(part.strip())
        return value


def encode_macro(actions, resolve):
    out = bytearray()
    for action in actions:
        kind, args = action[0], action[1:]
        if kind == 'text':
            out += args[0].encode('utf-8')
        elif kind in ('tap', 'down', 'up'):
            for name in args:
                kc = resolve(name)
                if kc < 256:
                    out += bytes([SS_QMK_PREFIX, {'tap': SS_TAP, 'down': SS_DOWN, 'up': SS_UP}[kind], kc])
                else:
                    lo, hi = kc & 0xFF, kc >> 8
                    if lo == 0:  # no zero bytes: 0xXX00 travels as 0xFFXX
                        lo, hi = hi, 0xFF
                    out += bytes([SS_QMK_PREFIX, {'tap': EXT_TAP, 'down': EXT_DOWN, 'up': EXT_UP}[kind], lo, hi])
        elif kind == 'delay':
            ms = int(args[0])
            out += bytes([SS_QMK_PREFIX, SS_DELAY, ms % 255 + 1, ms // 255 + 1])
        else:
            raise ValueError('unknown macro action ' + kind)
    if 0 in out:
        raise ValueError('macro contains a zero byte')
    return bytes(out) + b'\0'


def last_used(entries, empty):
    n = len(entries)
    while n > 0 and empty(entries[n - 1]):
        n -= 1
    return entries[:n]


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding='utf-8') as f:
        vil = json.load(f)
    resolve = Resolver(*load_names(sys.argv[2]))

    out = []
    w = out.append
    w('// Generated by tools/vil_to_c.py from %s. Do not edit.' % sys.argv[1].replace('\\', '/').split('/')[-1])
    w('#pragma once')
    w('')
    layers = vil['layout']
    w('#define KQ_DEFAULT_LAYER_COUNT %d' % len(layers))
    w('_Static_assert(KQ_DEFAULT_LAYER_COUNT == DYNAMIC_KEYMAP_LAYER_COUNT, "default.vil layer count");')
    w('_Static_assert(MATRIX_ROWS == %d && MATRIX_COLS == %d, "default.vil matrix size");'
      % (len(layers[0]), len(layers[0][0])))
    w('')
    w('#ifdef KQ_DEFAULT_KEYMAP')
    w('const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {')
    for layer in layers:
        w('    {')
        for row in layer:
            w('        {' + ', '.join('0x%04X' % resolve(k) for k in row) + '},')
        w('    },')
    w('};')
    w('#endif')
    w('')
    w('#ifdef KQ_DEFAULT_DATA')

    td = last_used(vil.get('tap_dance', []), lambda t: all(resolve(k) == 0 for k in t[:4]))
    w('static const vial_tap_dance_entry_t kq_default_tap_dance[] = {')
    for t in td:
        w('    {0x%04X, 0x%04X, 0x%04X, 0x%04X, %d},' % (resolve(t[0]), resolve(t[1]), resolve(t[2]), resolve(t[3]), t[4]))
    w('};')
    w('#define KQ_DEFAULT_TAP_DANCE_COUNT %d' % len(td))
    w('')

    combos = last_used(vil.get('combo', []), lambda c: all(resolve(k) == 0 for k in c))
    w('static const vial_combo_entry_t kq_default_combos[] = {')
    for c in combos:
        w('    {{0x%04X, 0x%04X, 0x%04X, 0x%04X}, 0x%04X},' % tuple(resolve(k) for k in c))
    w('};')
    w('#define KQ_DEFAULT_COMBO_COUNT %d' % len(combos))
    w('')

    kos = last_used(vil.get('key_override', []), lambda k: resolve(k.get('trigger', 0)) == 0)
    w('static const vial_key_override_entry_t kq_default_key_overrides[] = {')
    for k in kos:
        w('    {0x%04X, 0x%04X, 0x%04X, 0x%02X, 0x%02X, 0x%02X, 0x%02X},' % (
            resolve(k['trigger']), resolve(k['replacement']), k['layers'], k['trigger_mods'],
            k['negative_mod_mask'], k['suppressed_mods'], k['options']))
    w('};')
    w('#define KQ_DEFAULT_KEY_OVERRIDE_COUNT %d' % len(kos))
    w('')

    macros = vil.get('macro', [])
    buf = b''.join(encode_macro(m, resolve) for m in macros)
    w('/* %d macros, each ending in a zero byte. */' % len(macros))
    w('static const uint8_t kq_default_macros[] = {')
    for i in range(0, len(buf), 16):
        w('    ' + ', '.join('0x%02X' % b for b in buf[i:i + 16]) + ',')
    w('};')
    w('')

    settings = sorted((int(k), int(v)) for k, v in vil.get('settings', {}).items())
    w('static const struct {')
    w('    uint16_t qsid;')
    w('    uint32_t value;')
    w('} kq_default_settings[] = {')
    for qsid, value in settings:
        w('    {%d, %d},' % (qsid, value))
    w('};')
    w('#endif')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
